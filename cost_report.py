"""AI pipeline review: measured tokens and cost per run, projected daily and annual cost, and ROI.

Token counts come from output/**/audit.jsonl, which agent.py writes for every Claude call, so the per-run
figures are measured, not estimated. The projections and ROI scale those measurements with the
assumptions in ASSUMPTIONS below; change them to match the site.

Usage:
  python cost_report.py                    # print the review
  python cost_report.py --write-appendix   # also write appendix/pipeline-review.md
"""

import argparse
import json
from collections import defaultdict
from datetime import datetime

import agent

# USD per million tokens (input, output), Claude API list prices. Output includes thinking tokens.
PRICES = {
    "claude-opus-5-5": (4.00, 20.00),
    "claude-opus-5": (5.00, 25.00),
    "claude-opus-4-8": (5.00, 25.00),
    "claude-sonnet-5-5": (2.00, 10.00),
}

ASSUMPTIONS = {
    # How many new reports a day the plant files. The sample has 20 reports over six weeks with one robot;
    # Wien Energie is moving to five robots across three plants.
    "scenarios": {"One robot, quiet": 1, "One robot, busy": 5, "Robot fleet": 20},
    "manual_triage_minutes_per_report": 15,  # read, categorise, check for duplicates, write up the ticket
    "review_minutes_per_report": 3,          # robotics lead reviews the agent's draft instead
    "engineer_rate_usd_per_hour": 90,        # loaded cost of the person doing triage
    "upkeep_hours_per_month": 4,             # prompt tweaks, connector fixes, eval reruns
    "callout_hours": 2,                      # minimum charge per callout, from the reports
    "callout_rate_usd_per_hour": 120,        # on-call overtime rate
}


def load_runs(path):
    """Split an audit log into runs: each run_start event and the Claude calls after it."""
    runs = []
    for line in path.read_text().splitlines():
        event = json.loads(line)
        if event["event"] == "run_start":
            runs.append({"start": event, "calls": []})
        elif event["event"] == "claude_call" and runs:
            runs[-1]["calls"].append(event)
    for run in runs:
        # Older log lines have no step; calls run classify -> group -> ticket, so infer it from position.
        n = run["start"]["items"]
        for i, call in enumerate(run["calls"]):
            call.setdefault("step", "classify" if i < n else "group" if i == n else "ticket")
    return [r for r in runs if r["calls"] and r["start"].get("kind") != "eval"]


def cost(call):
    price_in, price_out = PRICES[call["model"]]
    return (call["input_tokens"] * price_in + call["output_tokens"] * price_out) / 1_000_000


def summarise(run, label):
    steps = defaultdict(lambda: {"calls": 0, "input": 0, "output": 0, "cost": 0.0})
    for call in run["calls"]:
        s = steps[call["step"]]
        s["calls"] += 1
        s["input"] += call["input_tokens"]
        s["output"] += call["output_tokens"]
        s["cost"] += cost(call)
    start = datetime.fromisoformat(run["start"]["ts"])
    end = datetime.fromisoformat(run["calls"][-1]["ts"])
    total = {k: sum(s[k] for s in steps.values()) for k in ("calls", "input", "output", "cost")}
    return {"label": label, "items": run["start"]["items"], "steps": dict(steps), "total": total,
            "minutes": (end - start).total_seconds() / 60, "model": run["calls"][0]["model"]}


def money(x):
    return f"${x:,.2f}" if x < 100 else f"${x:,.0f}"


def render(runs, backlog):
    a = ASSUMPTIONS
    basis = runs[-1]
    per_report = sum(r["total"]["cost"] for r in runs) / sum(r["items"] for r in runs)
    tokens_per_report = sum(r["total"]["input"] + r["total"]["output"] for r in runs) / sum(r["items"] for r in runs)
    lines = [
        "# AI pipeline review",
        "",
        "[← Back to README](../README.md)",
        "",
        "_Generated by `python cost_report.py --write-appendix` from the audit logs of real runs. "
        "Token counts and per-run costs are measured; projections and ROI depend on the assumptions listed below._",
        "",
        "## Measured: one run",
        "",
        f"Model `{basis['model']}` at ${PRICES[basis['model']][0]:.2f} per million input tokens and "
        f"${PRICES[basis['model']][1]:.2f} per million output tokens (output includes the model's thinking).",
        "",
        "| Run | Reports | API calls | Input tokens | Output tokens | Cost | Wall time |",
        "|---|---:|---:|---:|---:|---:|---:|",
        *[f"| {r['label']} | {r['items']} | {r['total']['calls']} | {r['total']['input']:,} | {r['total']['output']:,} "
          f"| {money(r['total']['cost'])} | {r['minutes']:.1f} min |" for r in runs],
        "",
        f"Where the tokens go in the {basis['label'].lower()}:",
        "",
        "| Step | Calls | Input tokens | Output tokens | Cost | Share of cost |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for step in ("classify", "group", "ticket"):
        s = basis["steps"].get(step)
        if s:
            lines.append(f"| {step} | {s['calls']} | {s['input']:,} | {s['output']:,} | {money(s['cost'])} | "
                         f"{s['cost'] / basis['total']['cost']:.0%} |")
    lines += [
        "",
        f"Across these runs the pipeline costs **{money(per_report)} per report** "
        f"(about {tokens_per_report:,.0f} tokens), including its share of the merge and ticket steps.",
        "",
        "## Projected: running every day",
        "",
        "Run once a day on that day's new reports (`ingest.py --since yesterday`, then `agent.py`). "
        "Cost scales with the number of reports, so the projection is reports per day × the measured cost per report.",
        "",
        "| Scenario | Reports / day | API cost / day | API cost / month | API cost / year |",
        "|---|---:|---:|---:|---:|",
    ]
    for name, n in a["scenarios"].items():
        lines.append(f"| {name} | {n} | {money(n * per_report)} | {money(n * per_report * 30.4)} | "
                     f"{money(n * per_report * 365)} |")

    saved_hours_per_report = (a["manual_triage_minutes_per_report"] - a["review_minutes_per_report"]) / 60
    upkeep = a["upkeep_hours_per_month"] * 12 * a["engineer_rate_usd_per_hour"]
    lines += [
        "",
        "## ROI",
        "",
        "Counted: engineer time saved on triage, minus API cost and upkeep. Not counted: the value of the fixes "
        "themselves, which is shown separately below because it depends on engineering acting on the backlog.",
        "",
        "| Scenario | Triage hours saved / year | Value of time saved | API cost / year | Upkeep / year | Net / year | ROI |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for name, n in a["scenarios"].items():
        hours = n * 365 * saved_hours_per_report
        value = hours * a["engineer_rate_usd_per_hour"]
        api = n * per_report * 365
        spend = api + upkeep
        lines.append(f"| {name} | {hours:,.0f} | {money(value)} | {money(api)} | {money(upkeep)} | "
                     f"{money(value - spend)} | {(value - spend) / spend:.1f}× |")
    callouts = sum(t["impact"]["false_alarm_callouts_per_month"] for t in backlog)
    readings = sum(t["impact"]["missed_measurement_points_per_week"] for t in backlog)
    callout_value = callouts * 12 * a["callout_hours"] * a["callout_rate_usd_per_hour"]
    lines += [
        "",
        "ROI = (value of time saved − API cost − upkeep) ÷ (API cost + upkeep). At these volumes the API bill is "
        "small next to upkeep, so the case rests on report volume and on how long manual triage really takes. "
        "Measure the manual time for a few weeks before relying on these numbers.",
        "",
        "**What the current backlog points at** (from the agent's own impact estimates, if every issue were fixed):",
        "",
        f"- about {callouts} false-alarm callouts a month avoided, roughly {money(callout_value)} a year in on-call "
        f"overtime at {a['callout_hours']} h × ${a['callout_rate_usd_per_hour']}/h;",
        f"- about {readings} missed or unusable readings a week recovered, about {readings * 52:,} a year.",
        "",
        "## Assumptions",
        "",
        "| Assumption | Value |",
        "|---|---|",
        *[f"| Reports per day: {name} | {n} |" for name, n in a["scenarios"].items()],
        f"| Manual triage time per report | {a['manual_triage_minutes_per_report']} min |",
        f"| Review time per report with the agent | {a['review_minutes_per_report']} min |",
        f"| Engineer cost | ${a['engineer_rate_usd_per_hour']}/h |",
        f"| Pipeline upkeep | {a['upkeep_hours_per_month']} h/month |",
        f"| Callout | {a['callout_hours']} h minimum at ${a['callout_rate_usd_per_hour']}/h |",
        "",
        "Edit `ASSUMPTIONS` in [cost_report.py](../cost_report.py) and re-run to update this page.",
        "",
        "## Ways to cut the API cost",
        "",
        "- **Lower effort for classification.** Classification is a short, well-specified task; run it at `low` "
        "effort (`SPOT_AGENT_EFFORT=low`) and re-check accuracy with `eval.py`.",
        "- **Batch API.** A once-a-day job doesn't need instant answers, and batch requests cost half. The "
        "server-side refusal fallback isn't available on batches, so refusals would need a manual retry.",
        "- **Prompt caching.** The instructions are repeated on every classify call; caching them helps once they "
        "grow past the minimum cacheable length.",
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write-appendix", action="store_true", help="write appendix/pipeline-review.md")
    args = parser.parse_args()

    runs = []
    for path, label in ((agent.OUT_DIR / "audit.jsonl", "Evaluation set"),
                        (agent.OUT_DIR / "live" / "audit.jsonl", "Live inbox (redacted)")):
        if path.exists():
            runs += [summarise(r, label) for r in load_runs(path)[-1:]]
    if not runs:
        raise SystemExit("No audited runs found. Run agent.py first.")
    backlog = json.loads((agent.OUT_DIR / "backlog.json").read_text())
    report = render(runs, backlog)
    print(report)
    if args.write_appendix:
        (agent.ROOT / "appendix" / "pipeline-review.md").write_text(report)


if __name__ == "__main__":
    main()
